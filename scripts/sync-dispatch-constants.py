#!/usr/bin/env python3
"""Rewrite the backend RPC dispatch constants in ServiceCatalog.swift and
AnkiBackend.swift from a generated anki backend.rs.

Service and method indices are positional in anki-upstream's .proto service
definitions, so an anki-upstream bump (or a fork such as JSchoreels/anki that
adds RPCs) that inserts a method silently shifts every index after it. This
script re-derives each Swift constant from its name (camelCase -> snake_case)
and fails if a name has no matching RPC, so drift is a build error instead of
a wrong RPC at runtime.

backend.rs is generated by anki's build script, e.g.
anki-bridge-rs/target/aarch64-apple-ios/release/build/anki-*/out/backend.rs

Usage: scripts/sync-dispatch-constants.py <backend.rs> [--check]
  --check  only report; exit 1 if any constant is out of date
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SWIFT_FILES = [
    ROOT / "Sources/AnkiProtoBridge/ServiceCatalog.swift",
    ROOT / "Sources/AnkiBackend/AnkiBackend.swift",
]

# Swift enums listing service IDs; each constant names a backend service.
SERVICE_ENUMS = {"ServiceID", "Service"}
# Swift method enums -> backend service (snake_case, without backend_/_service).
METHOD_ENUMS = {
    "CollectionOpsMethod": "collection",
    "CollectionMethod": "collection",
    "CardsMethod": "cards",
    "DecksMethod": "decks",
    "SchedulerMethod": "scheduler",
    "DeckConfigMethod": "deck_config",
    "NotetypesMethod": "notetypes",
    "StatsMethod": "stats",
    "ImportExportMethod": "import_export",
    "NotesMethod": "notes",
    "SearchMethod": "search",
    "SyncMethod": "sync",
    "TagsMethod": "tags",
    "ImageOcclusionMethod": "image_occlusion",
    "MediaMethod": "media",
    "CardRenderingMethod": "card_rendering",
    "ConfigMethod": "config",
}
# Implemented by anki-bridge-rs itself, not by the anki backend.
SKIPPED_ENUMS = {"AuxMethod"}
SKIPPED_SERVICES = {"aux"}
# Swift names that don't follow the RPC's name.
ALIASES = {
    ("CollectionMethod", "open"): "open_collection",
    ("CollectionMethod", "close"): "close_collection",
    ("DecksMethod", "getDeckTree"): "deck_tree",
}


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def parse_backend(src: str) -> tuple[dict[str, int], dict[str, dict[str, int]]]:
    services = {
        name: int(idx)
        for idx, name in re.findall(
            r"(\d+)\s*=>\s*self\.run_(backend_[a-z0-9_]+_service)_method\(", src
        )
    }
    methods: dict[str, dict[str, int]] = {}
    chunks = re.split(r"fn run_(backend_[a-z0-9_]+_service)_method\b", src)
    for name, body in zip(chunks[1::2], chunks[2::2]):
        body = body.split("\n    pub", 1)[0].split("\n    fn ", 1)[0]
        arms = re.split(r"\n\s*(\d+)\s*=>\s*\{", body)
        table = methods.setdefault(name, {})
        for idx, arm in zip(arms[1::2], arms[2::2]):
            call = re.search(r"::([a-z][a-z0-9_]*)\(\s*self\s*[,)]", arm)
            if call:
                table[call.group(1)] = int(idx)
    if not services or not methods:
        sys.exit("error: no dispatch table found; is this anki's generated backend.rs?")
    return services, methods


def expected(enum, const, services, methods):
    if enum in SERVICE_ENUMS:
        if const in SKIPPED_SERVICES:
            return None
        key = f"backend_{snake(const)}_service"
        if key not in services:
            raise KeyError(f"{enum}.{const}: no service {key}")
        return services[key]
    service = f"backend_{METHOD_ENUMS[enum]}_service"
    rpc = ALIASES.get((enum, const), snake(const))
    if rpc not in methods.get(service, {}):
        raise KeyError(f"{enum}.{const}: no method {rpc} in {service}")
    return methods[service][rpc]


def sync_file(path: Path, services, methods, errors: list[str]) -> tuple[str, list[str]]:
    text = path.read_text()
    changes: list[str] = []
    enum_re = re.compile(r"(\benum\s+(\w+)\s*\{)(.*?)(\n\s*\})", re.S)

    def fix_enum(m: re.Match) -> str:
        enum = m.group(2)
        if enum in SKIPPED_ENUMS:
            return m.group(0)
        if enum not in SERVICE_ENUMS and enum not in METHOD_ENUMS:
            if re.search(r"static let \w+: UInt32 = \d+", m.group(3)):
                errors.append(f"{path.name}: unknown dispatch enum {enum}")
            return m.group(0)

        def fix_const(c: re.Match) -> str:
            const, old = c.group(2), int(c.group(3))
            try:
                new = expected(enum, const, services, methods)
            except KeyError as err:
                errors.append(f"{path.name}: {err}")
                return c.group(0)
            if new is None or new == old:
                return c.group(0)
            changes.append(f"{path.name}: {enum}.{const} {old} -> {new}")
            return f"{c.group(1)}{new}"

        body = re.sub(r"(static let (\w+): UInt32 = )(\d+)", fix_const, m.group(3))
        return m.group(1) + body + m.group(4)

    return enum_re.sub(fix_enum, text), changes


def main() -> None:
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    if len(args) != 1:
        sys.exit(__doc__)
    services, methods = parse_backend(Path(args[0]).read_text())

    errors: list[str] = []
    all_changes: list[str] = []
    for path in SWIFT_FILES:
        new_text, changes = sync_file(path, services, methods, errors)
        all_changes += changes
        if changes and not check:
            path.write_text(new_text)

    for line in all_changes:
        print(line)
    if errors:
        sys.exit("error: unresolved dispatch constants:\n  " + "\n  ".join(errors))
    if check and all_changes:
        sys.exit(f"error: {len(all_changes)} dispatch constants are out of date")
    verb = "would change" if check else "updated"
    print(f"dispatch constants: {len(all_changes)} {verb}")


if __name__ == "__main__":
    main()
